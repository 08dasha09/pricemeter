package org.viewer.pricemeter.catalog.domain;

/**
 * Стан зіставлення пропозиції магазину з товарною позицією.
 */
public enum MatchStatus {
    /** Ще не зіставлено або очікує ручної перевірки. */
    PENDING,
    /** Зіставлено автоматично з достатньою впевненістю. */
    AUTO,
    /** Зіставлення підтверджено або змінено вручну. */
    MANUAL,
    /** Автоматичне зіставлення відхилено вручну. */
    REJECTED
}
