package org.viewer.pricemeter.pricehistory.service;

/**
 * Що сталося з історією після запису спостереження.
 */
public enum RecordOutcome {
    /** Стан ціни змінився (або це перше спостереження) — створено новий інтервал. */
    NEW_STATE,
    /** Стан не змінився — подовжено поточний інтервал. */
    UNCHANGED,
    /** Спостереження старіше за останній відомий стан — проігноровано. */
    OUT_OF_ORDER
}
